//! The "Leo guest tools" CD every new space is created with.
//!
//! What a guest needs to come up as a satellite with nobody at the console:
//! the drivers Windows Setup lacks for a virtio disk and NIC
//! (`$WinPEDriver$`, lifted from the virtio-win image on the host), an
//! `autounattend.xml` that partitions, installs, names the machine, makes a
//! local admin and runs the CD's own first-logon script, the Leo satellite
//! for the guest's platform with its installer, and — when the hub answered
//! in time — the satellite's pairing already done (`satellite.env`). Built
//! per space, because the name, the password and the token are in it, and
//! attached as a CD-ROM beside the installer so it is there from the first
//! boot with nothing to download from inside the guest.
//!
//! Three parties and one rule: this process stages the files as `leo` under
//! `/var/lib/leo/spaces-import/guest-tools/<space>/` on the host, the root
//! helper (`build-guest-tools`) packs that directory into the root-owned
//! media directory, and root never takes an address from a request — the
//! hub host the guest should dial is written by this process into a file the
//! helper merely copies.
//!
//! **Pairing, zero-touch.** At create this process asks the hub for a pairing
//! code (the same unauthenticated request a Mac makes), the create reply
//! carries the code, and the sheet's chained action approves it with the
//! session of the admin who clicked — the one thing this process cannot do,
//! since the proxy strips the caller's token. Then [`finish_pairing`] polls
//! the code, writes the token into `satellite.env` and rebuilds the CD,
//! all before the guest has been started. A guest started too early, or a
//! code never approved, falls back to the installer pairing interactively.
//!
//! The binaries come from [`tools_dir`] on the hub — `leo-satellited.exe`
//! for Windows, `leo-satellited` for Linux — which `leo push`/the release
//! lay down. With neither present the CD is not built and the create says
//! so, rather than shipping an installer with nothing to install.

use std::path::{Path, PathBuf};

use crate::facts::Facts;
use crate::host::{Host, HostError};
use crate::provision::STATE_DIR;

/// Where the satellite binaries live on the hub. `LEO_GUEST_TOOLS_DIR`
/// overrides; the default is beside the hub's other machine-wide state.
pub fn tools_dir() -> PathBuf {
    std::env::var_os("LEO_GUEST_TOOLS_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("/var/lib/leo/guest-tools"))
}

/// The staging directory on the host, the one `build-guest-tools` reads.
pub fn staging_dir(name: &str) -> String {
    format!("/var/lib/leo/spaces-import/guest-tools/{name}")
}

/// Where the built CD lands.
pub fn iso_path(name: &str) -> String {
    format!("{STATE_DIR}/iso/guest-tools-{name}.iso")
}

const INSTALL_PS1: &str = include_str!("../scripts/guest-tools/install-leo-satellite.ps1");
const INSTALL_SH: &str = include_str!("../scripts/guest-tools/install-leo-satellite.sh");
const AUTOUNATTEND: &str = include_str!("../scripts/guest-tools/autounattend.xml");
const FIRST_LOGON: &str = include_str!("../scripts/guest-tools/first-logon.cmd");

/// The one generic installation key Microsoft publishes for Pro: it picks
/// the edition at setup and activates nothing — the person's own key goes
/// in afterwards. Without any key, a multi-edition ISO stops to ask.
const GENERIC_PRO_KEY: &str = "VK7JG-NPHTM-C97JM-9MPGT-3V66T";

/// What a space asked for, as far as the CD cares.
#[derive(Debug, Clone, Default)]
pub struct GuestPlan {
    pub os: String,
    pub product_key: Option<String>,
    /// The local admin's password, generated by [`new_password`].
    pub admin_password: String,
    /// A pairing the hub has already issued a token for.
    pub satellite_env: Option<String>,
}

/// Twenty characters from the kernel's randomness, in an alphabet with no
/// look-alikes — this is read off a pane and typed at a console.
pub fn new_password() -> String {
    const ALPHABET: &[u8] = b"abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
    let mut bytes = [0u8; 20];
    if let Ok(mut f) = std::fs::File::open("/dev/urandom") {
        use std::io::Read;
        let _ = f.read_exact(&mut bytes);
    }
    bytes
        .iter()
        .map(|b| ALPHABET[*b as usize % ALPHABET.len()] as char)
        .collect()
}

/// Which `virtio-win` driver directory matches an OS id.
pub fn virtio_dir(os: &str) -> Option<&'static str> {
    Some(match os {
        "win11" => "w11",
        "win10" => "w10",
        "win2k25" => "2k25",
        "win2k22" => "2k22",
        "win2k19" => "2k19",
        _ => return None,
    })
}

/// A NetBIOS-safe computer name from a space name: letters, digits and
/// hyphens, fifteen at most, never starting with a hyphen.
pub fn computer_name(space: &str) -> String {
    let mut s: String = space
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .take(15)
        .collect();
    while s.starts_with('-') {
        s.remove(0);
    }
    if s.is_empty() {
        s = "leo-space".into();
    }
    s
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// The unattend file for one Windows space.
///
/// Client Windows selects its edition by product key — the person's own, or
/// the generic Pro key, which installs and activates nothing. Server
/// evaluation media has no edition to key-select and would refuse a retail
/// key at setup, so it takes image 2 (Standard, Desktop Experience) and the
/// key, when there is one, is applied at first logon by `leo-set-edition.cmd`.
pub fn render_unattend(space: &str, plan: &GuestPlan) -> String {
    let server = plan.os.starts_with("win2k");
    let key = plan
        .product_key
        .as_deref()
        .map(str::trim)
        .filter(|k| !k.is_empty());
    let (install_from, product_key) = if server {
        (
            r#"<InstallFrom><MetaData wcm:action="add"><Key>/IMAGE/INDEX</Key><Value>2</Value></MetaData></InstallFrom>"#.to_string(),
            String::new(),
        )
    } else {
        (
            String::new(),
            format!(
                "<ProductKey><Key>{}</Key><WillShowUI>Never</WillShowUI></ProductKey>",
                xml_escape(key.unwrap_or(GENERIC_PRO_KEY))
            ),
        )
    };
    AUTOUNATTEND
        .replace("{{install_from}}", &install_from)
        .replace("{{product_key}}", &product_key)
        .replace("{{computer_name}}", &xml_escape(&computer_name(space)))
        .replace("{{password}}", &xml_escape(&plan.admin_password))
}

/// The first-logon edition change for Server media with a key: evaluation
/// to the licensed Standard edition, which is what the key is for.
pub fn render_set_edition(plan: &GuestPlan) -> Option<String> {
    if !plan.os.starts_with("win2k") {
        return None;
    }
    let key = plan
        .product_key
        .as_deref()
        .map(str::trim)
        .filter(|k| !k.is_empty())?;
    if !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        return None;
    }
    Some(format!(
        "@echo off\r\nDISM /online /Set-Edition:ServerStandard /ProductKey:{key} /AcceptEula /NoRestart\r\n"
    ))
}

/// The binaries on the hub, by the name each is shipped under.
pub fn binaries(dir: &Path) -> Vec<PathBuf> {
    ["leo-satellited.exe", "leo-satellited"]
        .iter()
        .map(|f| dir.join(f))
        .filter(|p| p.is_file())
        .collect()
}

/// The address a guest on this host should dial to reach the hub.
///
/// A guest sits behind libvirt's NAT on the host, so "the hub" is the hub
/// as the host sees it: for a remote host, the address this process's SSH
/// session arrived from (`$SSH_CONNECTION`), which is the hub's address on
/// the LAN the host is on; for a local host, the NAT bridge itself, where
/// the hub answers. `spaces_guest_hub` overrides both for a hub that is
/// reached some other way.
pub async fn hub_host(host: &Host, override_setting: Option<&str>) -> Result<String, HostError> {
    if let Some(h) = override_setting.map(str::trim).filter(|s| !s.is_empty()) {
        return Ok(h.to_string());
    }
    match host {
        Host::Local => Ok("192.168.122.1".to_string()),
        Host::Remote { .. } => {
            let out = host.run("printf '%s' \"${SSH_CONNECTION%% *}\"").await?;
            let addr = out.trimmed().trim().to_string();
            if addr.is_empty() {
                Ok(host
                    .to_string()
                    .rsplit('@')
                    .next()
                    .unwrap_or("")
                    .to_string())
            } else {
                Ok(addr)
            }
        }
    }
}

/// Why a CD could not be built — said in the create's reply, never fatal:
/// a space with no guest tools is still a space.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Skipped {
    NoBinaries(PathBuf),
    NoPrivilege,
    Failed(String),
}

impl std::fmt::Display for Skipped {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::NoBinaries(d) => write!(
                f,
                "no guest tools CD: no satellite binaries under {} on the hub (leo-satellited.exe / leo-satellited)",
                d.display()
            ),
            Self::NoPrivilege => write!(f, "no guest tools CD: the host grants no helper to build one"),
            Self::Failed(why) => write!(f, "no guest tools CD: {why}"),
        }
    }
}

fn io_err(host: &Host, what: &str, e: std::io::Error) -> HostError {
    HostError::Spawn {
        host: host.to_string(),
        command: what.to_string(),
        source: e,
    }
}

/// Stage and build the CD for `name`. `Ok(Ok(path))` is the ISO on the
/// host; `Ok(Err(why))` is a space that goes without, and why.
pub async fn build(
    host: &Host,
    f: &Facts,
    name: &str,
    hub: &str,
    plan: &GuestPlan,
) -> Result<Result<String, Skipped>, HostError> {
    let dir = tools_dir();
    let bins = binaries(&dir);
    if bins.is_empty() {
        return Ok(Err(Skipped::NoBinaries(dir)));
    }
    let Some(verb) = f.privilege.wrap(&format!("build-guest-tools {name}")) else {
        return Ok(Err(Skipped::NoPrivilege));
    };

    let staging = staging_dir(name);
    let out = host
        .run(&format!(
            // A previous build may have left the drivers' read-only
            // directories behind (the image's own modes); `rm` needs them
            // writable first.
            "chmod -R u+w '{staging}' 2>/dev/null; rm -rf '{staging}' && mkdir -p '{staging}' && chmod 0700 '{staging}'"
        ))
        .await?;
    if !out.ok() {
        return Ok(Err(Skipped::Failed(out.failure())));
    }
    for bin in &bins {
        let file = bin
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("leo-satellited");
        host.upload(bin, &format!("{staging}/{file}")).await?;
    }

    // Windows: the drivers Setup lacks, lifted from the virtio-win image the
    // host already holds (it is root's but world-readable). Only the two
    // Setup itself needs; the guest tools installer brings the rest at first
    // logon. xorriso, not bsdtar: the image stores one driver build under
    // several names as ISO 9660 hard links (`viostor/w11/amd64/viostor.sys`
    // → `amd64/w11/viostor.sys`), and bsdtar extracting a subset fails on
    // every link whose target it was not asked for. xorriso reads the data
    // behind the link; it also keeps the image's read-only modes, hence the
    // chmod so a rebuild can replace the directory.
    if let Some(vdir) = virtio_dir(&plan.os) {
        let out = host
            .run(&format!(
                "mkdir -p '{staging}/$WinPEDriver$' && cd '{staging}/$WinPEDriver$' && \
                 xorriso -report_about WARNING -osirrox on:auto_chmod_on -indev {STATE_DIR}/iso/virtio-win.iso \
                 -extract /viostor/{vdir}/amd64 viostor -extract /NetKVM/{vdir}/amd64 NetKVM 2>&1 && \
                 chmod -R u+w . && test -f viostor/viostor.sys && test -f NetKVM/netkvm.sys"
            ))
            .await?;
        if !out.ok() {
            return Ok(Err(Skipped::Failed(format!(
                "could not lift the virtio drivers for {vdir}: {}",
                out.failure()
            ))));
        }
    }

    // The scripts and the facts, written as files: the helper copies a
    // directory and reads nothing in it.
    let scratch = std::env::temp_dir().join(format!("leo-spaces-guest-tools-{name}"));
    std::fs::create_dir_all(&scratch).map_err(|e| io_err(host, "stage guest tools", e))?;
    let crlf = |s: &str| s.replace("\r\n", "\n").replace('\n', "\r\n");
    let mut files: Vec<(&str, String)> = vec![
        ("install-leo-satellite.ps1", crlf(INSTALL_PS1)),
        ("install-leo-satellite.sh", INSTALL_SH.to_string()),
        ("leo-hub.txt", format!("{hub}\n")),
        ("leo-name.txt", format!("{name}\n")),
    ];
    if virtio_dir(&plan.os).is_some() {
        files.push(("autounattend.xml", render_unattend(name, plan)));
        files.push(("first-logon.cmd", crlf(FIRST_LOGON)));
        if let Some(cmd) = render_set_edition(plan) {
            files.push(("leo-set-edition.cmd", cmd));
        }
    }
    if let Some(env) = &plan.satellite_env {
        files.push(("satellite.env", env.clone()));
    }
    for (file, body) in &files {
        let local = scratch.join(file);
        std::fs::write(&local, body).map_err(|e| io_err(host, &format!("write {file}"), e))?;
        host.upload(&local, &format!("{staging}/{file}")).await?;
    }
    let _ = std::fs::remove_dir_all(&scratch);
    // The password, kept beside the staging for the pane to show an admin;
    // leo's own, like the directory.
    let out = host
        .run(&format!(
            "printf '%s' '{}' > '{staging}/admin-password.txt' && chmod 0600 '{staging}/admin-password.txt'",
            plan.admin_password.replace('\'', "")
        ))
        .await?;
    if !out.ok() {
        return Ok(Err(Skipped::Failed(out.failure())));
    }

    let out = host
        .run_with_timeout(&verb, std::time::Duration::from_secs(120))
        .await?;
    if !out.ok() {
        return Ok(Err(Skipped::Failed(out.failure())));
    }
    Ok(Ok(iso_path(name)))
}

// ── Pairing ────────────────────────────────────────────────────────────

/// Ask the hub for a pairing code for `name`. Unauthenticated by design —
/// it is the same request a Mac's setup screen makes — and rate-limited by
/// the hub, which is why one create asks exactly once.
pub async fn request_pairing(leo_api_url: &str, name: &str) -> Option<String> {
    let body = serde_json::json!({ "satellite_name": name, "platform": "" }).to_string();
    let reply = crate::config::hub_post(leo_api_url, "/api/satellite-pair", &body)
        .await
        .ok()?;
    serde_json::from_str::<serde_json::Value>(&reply)
        .ok()?
        .get("code")?
        .as_str()
        .map(str::to_string)
}

/// The `satellite.env` the Linux and Windows satellites both read.
pub fn satellite_env(hub: &str, port: u16, token: &str, name: &str) -> String {
    format!("LEO_HUB_HOST={hub}\nLEO_HUB_PORT={port}\nLEO_BRIDGE_TOKEN={token}\nLEO_SATELLITE_ID={name}\n")
}

/// Wait for the admin's approval of `code`, then put the token on the CD.
///
/// Runs after the create has answered, for up to the code's own lifetime.
/// Each poll is the hub's long-poll (25 s), so a ten-minute wait is a couple
/// of dozen requests — inside the hub's per-minute limit. On approval the
/// CD is rebuilt with `satellite.env`; the guest is not running yet in the
/// ordinary case, and libvirt opens the image at start, not at define.
pub async fn finish_pairing(
    host: Host,
    f: Facts,
    name: String,
    hub: String,
    plan: GuestPlan,
    leo_api_url: String,
    code: String,
) {
    let started = std::time::Instant::now();
    let mut plan = plan;
    while started.elapsed() < std::time::Duration::from_secs(600) {
        let Ok(reply) =
            crate::config::hub_get(&leo_api_url, &format!("/api/satellite-pair/{code}")).await
        else {
            tokio::time::sleep(std::time::Duration::from_secs(10)).await;
            continue;
        };
        let Ok(v) = serde_json::from_str::<serde_json::Value>(&reply) else {
            tokio::time::sleep(std::time::Duration::from_secs(10)).await;
            continue;
        };
        match v.get("status").and_then(|s| s.as_str()) {
            Some("approved") => {
                let token = v
                    .get("token")
                    .and_then(|t| t.as_str())
                    .unwrap_or("")
                    .to_string();
                let port = v.get("hub_port").and_then(|p| p.as_u64()).unwrap_or(8420) as u16;
                if token.is_empty() {
                    tracing::warn!(space = %name, "pairing approved but the hub sent no token");
                    return;
                }
                plan.satellite_env = Some(satellite_env(&hub, port, &token, &name));
                match build(&host, &f, &name, &hub, &plan).await {
                    Ok(Ok(_)) => {
                        tracing::info!(space = %name, "guest tools CD rebuilt with the satellite's pairing")
                    }
                    Ok(Err(why)) => tracing::warn!(space = %name, "{why}"),
                    Err(e) => tracing::warn!(space = %name, "rebuilding the guest tools CD: {e}"),
                }
                return;
            }
            Some("pending") => continue,
            other => {
                tracing::info!(space = %name, status = ?other, "pairing not completed — the installer will pair interactively");
                return;
            }
        }
    }
    tracing::info!(space = %name, "pairing code expired unapproved — the installer will pair interactively");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_local_hosts_guests_dial_the_nat_bridge() {
        let rt = tokio::runtime::Runtime::new().unwrap();
        assert_eq!(
            rt.block_on(hub_host(&Host::Local, None)).unwrap(),
            "192.168.122.1"
        );
        assert_eq!(
            rt.block_on(hub_host(&Host::Local, Some(" hub.example:8420 ")))
                .unwrap(),
            "hub.example:8420",
            "the setting overrides, trimmed"
        );
        assert_eq!(
            rt.block_on(hub_host(&Host::Local, Some("   "))).unwrap(),
            "192.168.122.1",
            "a blank setting is no setting"
        );
    }

    /// Only the binaries that are actually there — and nothing that is not
    /// a satellite binary, however it got into the directory.
    #[test]
    fn only_present_satellite_binaries_are_shipped() {
        let dir = std::env::temp_dir().join(format!("leo-guest-tools-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        assert!(binaries(&dir).is_empty());
        std::fs::write(dir.join("leo-satellited.exe"), b"MZ").unwrap();
        std::fs::write(dir.join("notes.txt"), b"x").unwrap();
        let got = binaries(&dir);
        assert_eq!(got.len(), 1);
        assert!(got[0].ends_with("leo-satellited.exe"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// The installers the CD carries say what they need: a hub and a name
    /// from the CD's own files, and the satellite binary beside them — and
    /// the Windows one takes the pairing from the CD when it is there.
    #[test]
    fn the_installers_read_the_cds_own_files() {
        for s in [INSTALL_PS1, INSTALL_SH] {
            assert!(s.contains("leo-hub.txt"), "the hub comes from the CD");
            assert!(s.contains("leo-name.txt"), "the name comes from the CD");
            assert!(s.contains("pair"), "the installer pairs");
        }
        assert!(INSTALL_PS1.contains("leo-satellited.exe"));
        assert!(
            INSTALL_PS1.contains("satellite.env"),
            "a token on the CD is used, not re-paired"
        );
        assert!(INSTALL_SH.contains("leo-satellited"));
        assert_eq!(
            iso_path("cad"),
            "/var/lib/leo-spaces/iso/guest-tools-cad.iso"
        );
    }

    /// Client Windows keys its edition (the generic Pro key when nobody gave
    /// one); Server evaluation media takes image 2 and keeps a given key for
    /// first logon. The password and name land where Setup reads them, and
    /// the first-logon command finds the CD by its own file.
    #[test]
    fn the_unattend_picks_the_edition_the_way_each_medium_needs() {
        let mut plan = GuestPlan {
            os: "win11".into(),
            admin_password: "pw<1>".into(),
            ..Default::default()
        };
        let xml = render_unattend("cad-box", &plan);
        assert!(
            xml.contains(&format!("<Key>{GENERIC_PRO_KEY}</Key>")),
            "no key given: the generic Pro key selects the edition"
        );
        assert!(!xml.contains("/IMAGE/INDEX"));
        assert!(xml.contains("<ComputerName>cad-box</ComputerName>"));
        assert!(
            xml.contains("<Value>pw&lt;1&gt;</Value>"),
            "the password is XML-escaped"
        );
        assert!(
            xml.contains("leo-name.txt"),
            "first logon finds the CD by its file"
        );
        assert!(render_set_edition(&plan).is_none());

        plan.product_key = Some("ABCDE-FGHIJ-KLMNO-PQRST-UVWXY".into());
        assert!(
            render_unattend("cad-box", &plan).contains("<Key>ABCDE-FGHIJ-KLMNO-PQRST-UVWXY</Key>")
        );

        plan.os = "win2k22".into();
        let xml = render_unattend("cad-box", &plan);
        assert!(
            xml.contains("/IMAGE/INDEX"),
            "server media selects by image"
        );
        assert!(
            !xml.contains("<ProductKey>"),
            "evaluation media refuses a retail key at setup"
        );
        let set =
            render_set_edition(&plan).expect("a key on server media is applied at first logon");
        assert!(set.contains("Set-Edition:ServerStandard") && set.contains("ABCDE-FGHIJ"));
        plan.product_key = Some("not a key; rm -rf".into());
        assert!(
            render_set_edition(&plan).is_none(),
            "a key with shell in it is not a key"
        );
    }

    #[test]
    fn names_passwords_and_drivers_have_the_right_shape() {
        assert_eq!(
            computer_name("engineering-workstation-01"),
            "engineering-wor"
        );
        assert_eq!(computer_name("--odd name!"), "oddname");
        assert_eq!(computer_name(""), "leo-space");
        let p = new_password();
        assert_eq!(p.len(), 20);
        assert!(
            p.chars().all(|c| c.is_ascii_alphanumeric()) && !p.contains(['0', 'O', 'l', 'I', '1'])
        );
        assert_eq!(virtio_dir("win11"), Some("w11"));
        assert_eq!(virtio_dir("win2k25"), Some("2k25"));
        assert_eq!(virtio_dir("ubuntu24.04"), None);
        let env = satellite_env("192.168.0.221", 8420, "tok", "cad");
        assert!(
            env.contains("LEO_HUB_HOST=192.168.0.221\n") && env.contains("LEO_BRIDGE_TOKEN=tok\n")
        );
    }
}
